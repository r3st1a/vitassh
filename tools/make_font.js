/*
 * Turns third_party/font8x8_basic.h into a self-contained src/font8x8.c, so
 * the application tree has no build-time dependency on third_party/.
 *
 *   node tools/make_font.js
 *
 * The source font is Daniel Hepper's font8x8, which is public domain and
 * derives from Marcel Sondaar's public-domain VGA fonts.
 */
'use strict';

const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const inputPath = path.join(root, 'third_party', 'font8x8_basic.h');
const outputPath = path.join(root, 'src', 'font8x8.c');

const FIRST = 0x20;
const LAST = 0x7e;

const source = fs.readFileSync(inputPath, 'utf8');

const glyphPattern = /\{\s*((?:0x[0-9a-fA-F]{2}\s*,\s*){7}0x[0-9a-fA-F]{2})\s*\}/g;
const all = [];
let match;

while ((match = glyphPattern.exec(source)) !== null) {
	all.push(match[1].split(',').map((byte) => byte.trim().toLowerCase()));
}

if (all.length !== 128) {
	throw new Error(`expected 128 glyphs in ${inputPath}, found ${all.length}`);
}

const label = (code) => {
	const ch = String.fromCharCode(code);
	if (ch === '\\') return 'backslash';
	if (ch === "'") return 'quote';
	if (ch === ' ') return 'space';
	return ch;
};

const lines = [];
lines.push('/*');
lines.push(' * 8x8 bitmap font covering ASCII 0x20-0x7E.');
lines.push(' *');
lines.push(" * Generated by tools/make_font.js from Daniel Hepper's font8x8, which is");
lines.push(' * public domain and derives from Marcel Sondaar\'s public-domain VGA fonts.');
lines.push(' * Do not edit by hand -- rerun the script instead.');
lines.push(' */');
lines.push('');
lines.push('#include "font8x8.h"');
lines.push('');
lines.push('/* One byte per row, top row first; bit 0 is the leftmost pixel. */');
lines.push('const uint8_t font8x8[FONT_GLYPHS][FONT_GLYPH_BYTES] = {');

for (let code = FIRST; code <= LAST; code++) {
	const bytes = all[code];
	const hex = bytes.map((b) => `${b},`).join(' ');
	const name = `0x${code.toString(16).padStart(2, '0')} '${label(code)}'`;

	lines.push(`\t{ ${hex} }, /* ${name.padEnd(12)} */`);
}

lines.push('};');
lines.push('');

fs.writeFileSync(outputPath, lines.join('\n'));
console.log(`wrote ${path.relative(root, outputPath)} (${LAST - FIRST + 1} glyphs)`);
